let inserted = 0;

for (const lang of ['zh', 'en', 'de', 'ru', 'ms', 'th', 'vi', 'id', 'fr', 'es', 'pt']) {
  const blockRe = new RegExp("(window\\.MN_I18N\\.add\\('" + lang + "', \\{\\r?\\n)([\\s\\S]*?)(\\r?\\n\\}\\);)", '');
  const m = out.match(blockRe);
  if (!m) { console.error('❌ 未找到 ' + lang + ' 块'); process.exit(1); }
  const body = m[2];
  // 已插入过？幂等：任何新键已存在则跳过该语言块
  if (body.includes('"fc.tag.pickLabel"')) { console.log('⏭ ' + lang + ' 已含新键，跳过'); continue; }
  const lines = body.split('\n');
  // 按字母序找每个新键的插入点（块内键已字母序）
  const sortedKeys = Object.keys(KEYS[lang]).sort();
  for (const k of sortedKeys) {
    const newLine = '  ' + JSON.stringify(k) + ': ' + JSON.stringify(KEYS[lang][k]) + ',';
    let idx = lines.length - 1; // 默认插在最后一行（通常是 '' 或最后键）之前
    for (let i = 0; i < lines.length; i++) {
      const km = lines[i].match(/^  "([^"]+)":/);
      if (!km) continue;
      if (km[1] > k) { idx = i; break; }
    }
    lines.splice(idx, 0, newLine);
  }
  out = out.replace(blockRe, (full, head, _b, tail) => head + lines.join('\n') + tail);
  inserted++;
}
if (!inserted) { console.log('无块需要插入（已全部存在）'); process.exit(0); }
